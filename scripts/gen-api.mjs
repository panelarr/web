// Generates the API types from the server's spec plus the drafts (see spec.mjs):
//
//   pnpm gen:api          writes src/api/schema.gen.ts and src/api/drafts.gen.ts
//   pnpm gen:api:check    fails when either is out of date (run by `make check`)
import { readFile, writeFile } from "node:fs/promises";
import openapiTS, { astToString } from "openapi-typescript";
import { loadSpec } from "./spec.mjs";

const header = `// Generated by scripts/gen-api.mjs from api/openapi.yaml and api/drafts/.
// Don't edit by hand: run \`make gen\`.
/* eslint-disable */
`;

const { spec, draftOps } = await loadSpec();
const schema = header + astToString(await openapiTS(spec, { alphabetize: false, defaultNonNullable: false }));
const drafts = `${header}
/** Operations that come from api/drafts/ and aren't in the server's spec yet. */
export const draftOperations: ReadonlyArray<{ method: string; path: string; operationId: string; file: string }> = ${JSON.stringify(draftOps, null, 2)};
`;

const outputs = [
  [new URL("../src/api/schema.gen.ts", import.meta.url), schema],
  [new URL("../src/api/drafts.gen.ts", import.meta.url), drafts],
];

if (process.argv.includes("--check")) {
  let stale = false;
  for (const [file, text] of outputs) {
    if ((await readFile(file, "utf8").catch(() => "")) !== text) {
      console.error(`${file.pathname.split("/web/").pop()} is out of date. Run \`make gen\`.`);
      stale = true;
    }
  }
  if (stale) process.exit(1);
  console.log("Generated API types are up to date.");
} else {
  for (const [file, text] of outputs) await writeFile(file, text);
  console.log(`Wrote the API types (${draftOps.length} draft operations).`);
}
